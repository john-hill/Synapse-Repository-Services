CREATE TABLE IF NOT EXISTS `COLUMN_ANALYZER_OVERRIDE` (
  `ID` BIGINT NOT NULL,
  `ETAG` char(36) NOT NULL,
  `ORGANIZATION_ID` BIGINT NOT NULL,
  `NAME` varchar(256) NOT NULL,
  `DESCRIPTION` varchar(1000) DEFAULT NULL,
  `OVERRIDES` JSON NOT NULL,
  `CREATED_BY` BIGINT NOT NULL,
  `CREATED_ON` TIMESTAMP(3) NOT NULL,
  `MODIFIED_BY` BIGINT NOT NULL,
  `MODIFIED_ON` TIMESTAMP(3) NOT NULL,
  PRIMARY KEY (`ID`),
  UNIQUE KEY `UNIQUE_CAO_ORG_NAME` (`ORGANIZATION_ID`, `NAME`),
  CONSTRAINT `CAO_ORG_FK` FOREIGN KEY (`ORGANIZATION_ID`) REFERENCES `ORGANIZATION` (`ID`) ON DELETE RESTRICT,
  CONSTRAINT `CAO_CREATED_BY_FK` FOREIGN KEY (`CREATED_BY`) REFERENCES `USER_GROUP` (`ID`) ON DELETE RESTRICT,
  CONSTRAINT `CAO_MODIFIED_BY_FK` FOREIGN KEY (`MODIFIED_BY`) REFERENCES `USER_GROUP` (`ID`) ON DELETE RESTRICT
)
